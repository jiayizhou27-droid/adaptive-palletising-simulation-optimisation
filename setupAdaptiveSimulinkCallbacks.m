function setupAdaptiveSimulinkCallbacks()
% setupAdaptiveSimulinkCallbacks Patch model callbacks for adaptive boxes.
%
% Run once after editing the helper functions. It saves the SLX so the
% model initializes layoutPlan/layoutPos/layoutYaw/boxDim from boxes.xlsx
% and spawns the first variable-size box.

model = "PalletizeBoxesUsingCobot";
load_system(model);

initFcn = strjoin({ ...
    'clear boxData boxDataAll boxTable layoutPlan layoutPos layoutYaw layoutH layoutN boxDim boxWeight boxPosition pickPosition boxToEEOffset suctionCenterOffsetCheck maxNumOfBoxes executionActionLog executionActorRegistry', ...
    'projectDir = fileparts(which(''PalletizeBoxesUsingCobot.slx''));', ...
    'if projectDir == ""', ...
    '    projectDir = pwd;', ...
    'end', ...
    'disp("Reading Excel from: " + fullfile(projectDir,"boxes.xlsx"));', ...
    'boxTable = readtable(fullfile(projectDir,"boxes.xlsx"));', ...
    'cfg = palletTaskConfig();', ...
    'EnableGeospatial = false;', ...
    'boxDataAll.length = boxTable.L;', ...
    'boxDataAll.width  = boxTable.W;', ...
    'boxDataAll.height = boxTable.H;', ...
    'boxDataAll.weight = boxTable.Mass;', ...
    'if ismember("Type", string(boxTable.Properties.VariableNames)); boxDataAll.type = string(boxTable.Type); end', ...
    'layoutBoxOffset = cfg.layoutBoxOffset;', ...
    'firstExcelID = cfg.firstExcelID;', ...
    'boxData = sliceBoxData(boxDataAll, firstExcelID);', ...
    'nLayoutBoxes = min(cfg.maxLayoutBoxes, numel(boxData.length));', ...
    'boxData.length = boxData.length(1:nLayoutBoxes);', ...
    'boxData.width = boxData.width(1:nLayoutBoxes);', ...
    'boxData.height = boxData.height(1:nLayoutBoxes);', ...
    'boxData.weight = boxData.weight(1:nLayoutBoxes);', ...
    'if isfield(boxData,"type"); boxData.type = boxData.type(1:nLayoutBoxes); end', ...
    'palletDim = cfg.palletDim;', ...
    'palletMargin = cfg.palletMargin;', ...
    'boxGap = cfg.boxGap;', ...
    'palletLoc = cfg.palletLoc;', ...
    'batchSize = cfg.batchSize;', ...
    'layoutPlan = buildLayoutPlanBatch3(boxData, palletDim, palletLoc, batchSize, palletMargin, boxGap);', ...
    'executionPlan = buildBufferExecutionPlan(layoutPlan, cfg);', ...
    'layoutN = numel(layoutPlan);', ...
    'layoutPos = zeros(layoutN,3);', ...
    'layoutYaw = zeros(layoutN,1);', ...
    'layoutH = zeros(layoutN,1);', ...
    'for i = 1:layoutN', ...
    '    layoutPos(i,:) = layoutPlan(i).pos;', ...
    '    layoutYaw(i) = layoutPlan(i).yaw;', ...
    '    layoutH(i) = layoutPlan(i).H;', ...
    'end', ...
    'boxDim = [boxData.length(1); boxData.width(1); boxData.height(1)];', ...
    'boxWeight = boxData.weight(1);', ...
    'boxPosition = cfg.sourceBoxPosition;', ...
    'pickPosition = cfg.pickPosition;', ...
    'boxToEEOffset = [-0.2 0 boxDim(3)/2 + 0.11];', ...
    'suctionCenterOffsetCheck = boxToEEOffset + [0.2 0 0];', ...
    'maxNumOfBoxes = numel(executionPlan);', ...
    'enableSimulinkRRT = false;', ...
    'executionActionLog = zeros(0,4);', ...
    'executionActorRegistry = cell(1,layoutN);', ...
    'rbt = exampleHelperSetUpCobot();', ...
    'assignin("base","boxData",boxData);', ...
    'assignin("base","boxDataAll",boxDataAll);', ...
    'assignin("base","layoutBoxOffset",layoutBoxOffset);', ...
    'assignin("base","firstExcelID",firstExcelID);', ...
    'assignin("base","palletDim",palletDim);', ...
    'assignin("base","palletMargin",palletMargin);', ...
    'assignin("base","boxGap",boxGap);', ...
    'assignin("base","palletLoc",palletLoc);', ...
    'assignin("base","layoutPlan",layoutPlan);', ...
    'assignin("base","executionPlan",executionPlan);', ...
    'assignin("base","batchSize",batchSize);', ...
    'assignin("base","layoutPos",layoutPos);', ...
    'assignin("base","layoutYaw",layoutYaw);', ...
    'assignin("base","layoutH",layoutH);', ...
    'assignin("base","layoutN",layoutN);', ...
    'assignin("base","boxDim",boxDim);', ...
    'assignin("base","boxWeight",boxWeight);', ...
    'assignin("base","boxPosition",boxPosition);', ...
    'assignin("base","pickPosition",pickPosition);', ...
    'assignin("base","boxToEEOffset",boxToEEOffset);', ...
    'assignin("base","suctionCenterOffsetCheck",suctionCenterOffsetCheck);', ...
    'assignin("base","maxNumOfBoxes",maxNumOfBoxes);', ...
    'assignin("base","enableSimulinkRRT",enableSimulinkRRT);', ...
    'assignin("base","executionActionLog",executionActionLog);', ...
    'assignin("base","executionActorRegistry",executionActorRegistry);', ...
    'assignin("base","rbt",rbt);', ...
    'assignin("base","EnableGeospatial",EnableGeospatial);' ...
    }, newline);

preLoadFcn = strjoin({ ...
    'EnableGeospatial = false;', ...
    'assignin("base","EnableGeospatial",EnableGeospatial);', ...
    'projectDir = fileparts(which(''PalletizeBoxesUsingCobot.slx''));', ...
    'if projectDir == ""', ...
    '    projectDir = pwd;', ...
    'end', ...
    'BoxSet = readtable(fullfile(projectDir,"boxes.xlsx"));', ...
    'assignin("base","BoxSet",BoxSet);' ...
    }, newline);

startFcn = strjoin({ ...
    'coder.extrinsic("spawnBox")', ...
    'coder.extrinsic("spawnBufferZone")', ...
    'coder.extrinsic("selectBoxDim")', ...
    '[boxDim, boxWeight] = selectBoxDim(0);', ...
    'boxToEEOffset = [-0.2 0 boxDim(3)/2 + 0.11];', ...
    'suctionCenterOffsetCheck = boxToEEOffset + [0.2 0 0];', ...
    'assignin("base","boxDim",boxDim);', ...
    'assignin("base","boxWeight",boxWeight);', ...
    'assignin("base","boxToEEOffset",boxToEEOffset);', ...
    'assignin("base","suctionCenterOffsetCheck",suctionCenterOffsetCheck);', ...
    'spawnBufferZone()', ...
    'spawnBox(0,boxPosition,boxDim)' ...
    }, newline);

stopFcn = strjoin({ ...
    'try', ...
    '    if exist("executionPlan","var") && ~isempty(executionPlan)', ...
    '        finalizeExecutionAction(numel(executionPlan)-1);', ...
    '    end', ...
    'catch ME', ...
    '    warning("PalletizeBoxes:FinalizeLastAction","%s",ME.message);', ...
    'end', ...
    'disp("Buffer execution simulation stopped.")' ...
    },newline);

set_param(model, "InitFcn", initFcn);
set_param(model, "PreLoadFcn", preLoadFcn);
set_param(model, "StartFcn", startFcn);
set_param(model, "StopFcn", stopFcn);
save_system(model, [], "OverwriteIfChangedOnDisk", true);

disp("Adaptive Simulink callbacks saved in " + model + ".slx");
end
